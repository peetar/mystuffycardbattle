/**
 * Calculates the exact health restored according to user specifications:
 * - If current health > 90% of maxHp: 100% full heal regardless of food.
 * - Else:
 *   - Favorite food: 75% of missing health
 *   - Mid food: 37.5% of missing health
 *   - Hated food: 25% of missing health
 */
export function calculateFoodHeal(
  currentHp: number,
  maxHp: number,
  preference: 'favorite' | 'mid' | 'hated'
): { healedAmount: number; newHp: number; message: string } {
  if (currentHp >= maxHp) {
    return { healedAmount: 0, newHp: maxHp, message: 'Already at maximum stuffing!' };
  }

  const missingHp = maxHp - currentHp;

  if (currentHp / maxHp > 0.90) {
    return {
      healedAmount: missingHp,
      newHp: maxHp,
      message: 'Above 90% HP! Full heal to 100% stuffing!',
    };
  }

  let ratio = 0.375;
  if (preference === 'favorite') {
    ratio = 0.75;
  } else if (preference === 'hated') {
    ratio = 0.25;
  }

  const rawHeal = Math.round(missingHp * ratio);
  const healedAmount = Math.max(1, Math.min(missingHp, rawHeal));
  const newHp = Math.min(maxHp, currentHp + healedAmount);

  let message = `Restored ${healedAmount} HP (${Math.round(ratio * 100)}% of missing fluff)!`;
  if (preference === 'favorite') {
    message = `FAVORITE FOOD! YUM! ${message}`;
  } else if (preference === 'hated') {
    message = `Yuck! Least favorite food... ${message}`;
  }

  return { healedAmount, newHp, message };
}
