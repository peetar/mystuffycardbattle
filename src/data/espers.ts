export function getRandomEspers(count: number = 3): Esper[] {
  const shuffled = [...ALL_ESPERS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count).map((e) => ({
    ...e,
    id: `esper_${e.id}_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
  }));
}

